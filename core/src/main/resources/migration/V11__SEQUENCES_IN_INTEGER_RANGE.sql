-- V2 started the sequences at 30000000000, which is outside the range of the INTEGER ID columns. Hibernate narrows the
-- sequence value to the int ID without a range check, so with the current Hibernate new IDs start at -64771072. Entries
-- from before V2 kept their positive IDs. The history cleanup deletes all entries with an ID lower than the highest ID
-- of the entries older than the retention time. One entry from before V2 is enough to make it delete all new history
-- every hour.
--
-- Each sequence restarts above the highest positive ID of its table, so new IDs are higher than all existing IDs. The
-- increment stays at 50.
--
-- This works on H2 2.1.x as well as 2.4.x. H2 ignores RESTART WITH NULL, so COALESCE is needed for empty tables and for
-- tables with only negative IDs.
ALTER SEQUENCE IDENTIFIER_KEY_VALUE_PAIR_SEQ RESTART WITH (SELECT COALESCE(MAX(ID), 0) + 50 FROM IDENTIFIER_KEY_VALUE_PAIR WHERE ID > 0);
ALTER SEQUENCE INDEXER_SEQ RESTART WITH (SELECT COALESCE(MAX(ID), 0) + 50 FROM INDEXER WHERE ID > 0);
